/** The wallet and the app must agree on the network, or the wallet refuses to sign ("network mismatch"). */
enum class Network(val label: String, val rpcUrl: String) {
    MAINNET("Mainnet", "https://api.mainnet-beta.solana.com"),
    DEVNET("Devnet", "https://api.devnet.solana.com"),
}

/**
 * Everything Solana-specific in the demo. The Squads instruction and both account decoders come from the
 * code generated by codama-kotlin; signing goes through Mobile Wallet Adapter (Seed Vault Wallet on the Seeker).
 */
class SquadsDemo(val network: Network) {
    private val rpc = SolanaRpc(network.rpcUrl)

    private val wallet = MobileWalletAdapter(
        connectionIdentity = ConnectionIdentity(
            identityUri = Uri.parse(IDENTITY_URI),
            iconUri = Uri.parse(IDENTITY_ICON),
            identityName = IDENTITY_NAME,
        ),
    ).apply { blockchain = if (network == Network.MAINNET) Solana.Mainnet else Solana.Devnet }

    /** Opens the wallet and returns the account the user chose. */
    suspend fun connect(sender: ActivityResultSender): SolanaPublicKey =
        when (val result = wallet.connect(sender)) {
            is TransactionResult.Success -> SolanaPublicKey(result.authResult.accounts.first().publicKey)
            is TransactionResult.NoWalletFound -> error("No Mobile Wallet Adapter wallet found")
            is TransactionResult.Failure -> error(result.message)
        }

    suspend fun balance(owner: SolanaPublicKey): Long = rpc.balance(owner)

    suspend fun airdrop(owner: SolanaPublicKey): String = rpc.requestAirdrop(owner, 1_000_000_000L)

    /** Squads' global config, decoded with the generated [ProgramConfig] decoder. */
    suspend fun programConfig(): Pair<SolanaPublicKey, ProgramConfig> {
        val address = findProgramConfigPda()
        val data = rpc.accountData(address) ?: error("No Squads ProgramConfig on ${network.label}")
        return address to ProgramConfig.decode(data)
    }

    /** The multisig whose create key is [owner], decoded with the generated [Multisig] decoder, or null. */
    suspend fun multisigOf(owner: SolanaPublicKey): Pair<SolanaPublicKey, Multisig?> {
        val address = findMultisigPda(owner)
        return address to rpc.accountData(address)?.let { Multisig.decode(it) }
    }

    private suspend fun createInstruction(owner: SolanaPublicKey, configAddress: SolanaPublicKey, config: ProgramConfig) =
        multisigCreateV2Instruction(
            programConfig = configAddress,
            treasury = config.treasury,
            multisig = findMultisigPda(owner),
            createKey = owner,
            creator = owner,
            configAuthority = null,
            threshold = 1u,
            members = listOf(Member(owner, Permissions(Permission.ALL))),
            timeLock = 0u,
            rentCollector = owner,
            // No memo: it would be written on chain and tag the user's wallet as having run this demo.
            memo = null,
        )

    /**
     * What the user is about to sign, read back from the instruction's bytes by the generated parser
     * (`parseSquadsMultisigProgramInstruction`), not from the values the app meant to put in.
     */
    suspend fun preview(owner: SolanaPublicKey): List<String> {
        val (configAddress, config) = programConfig()
        val ix = createInstruction(owner, configAddress, config)
        val short = { k: SolanaPublicKey -> k.base58().let { "${it.take(6)}…${it.takeLast(4)}" } }
        return when (val parsed = parseSquadsMultisigProgramInstruction(ix)) {
            is SquadsMultisigProgramInstruction.MultisigCreateV2 -> listOf(
                "Squads v4 · MultisigCreateV2",
                "New multisig: ${short(parsed.multisig)}",
                "Threshold ${parsed.threshold} of ${parsed.members.size} · time lock ${parsed.timeLock} s",
            ) + parsed.members.map { "Member ${short(it.key)} · ${permissions(it.permissions.mask)}" } + listOf(
                "Paid by: ${short(parsed.creator)} · rent back to: ${parsed.rentCollector?.let(short) ?: "nobody"}",
                "Memo: ${parsed.memo ?: "none"} · config authority: ${parsed.configAuthority?.let(short) ?: "none (members decide)"}",
            )
            null -> listOf("Not a Squads instruction this app can read.")
            else -> listOf("Squads v4 · ${parsed::class.simpleName}")
        }
    }

    /** The guard's findings on the transaction the app is about to ask the wallet to sign. */
    suspend fun alertsForCreate(owner: SolanaPublicKey): List<Alert> {
        val (configAddress, config) = programConfig()
        return TransactionGuard.check(listOf(createInstruction(owner, configAddress, config)), owner)
    }

    /**
     * What a wallet-draining site asks you to sign behind a "claim your airdrop" button, aimed at [owner]:
     * a harmless-looking 0.001 SOL fee, an unlimited spending permission, the ownership of a token account, and the
     * wallet itself handed to a program. Built only to be scanned: it is never signed nor sent.
     */
    suspend fun scanExampleScam(owner: SolanaPublicKey): List<Alert> {
        val attacker = SolanaPublicKey.from("Attack1111111111111111111111111111111111111")
        val usdc = SolanaPublicKey.from("EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v")
        val myUsdcAccount = findAssociatedTokenPda(owner, TokenProgram.PROGRAM_ID, usdc)
        val system = SolanaPublicKey.from("11111111111111111111111111111111")
        val fee = TransactionInstruction(
            system, listOf(AccountMeta(owner, true, true), AccountMeta(attacker, false, true)),
            byteArrayOf(2, 0, 0, 0) + ByteArray(8) { (1_000_000L shr (8 * it)).toByte() },
        )
        val assign = TransactionInstruction(system, listOf(AccountMeta(owner, true, true)), byteArrayOf(1, 0, 0, 0) + attacker.bytes)
        return TransactionGuard.check(
            listOf(
                fee,
                approveInstruction(myUsdcAccount, attacker, owner, amount = ULong.MAX_VALUE),
                setAuthorityInstruction(myUsdcAccount, owner, AuthorityType.ACCOUNT_OWNER, attacker),
                assign,
            ),
            owner,
        )
    }

    private fun permissions(mask: UByte): String = listOfNotNull(
        "initiate".takeIf { mask.toInt() and 1 != 0 },
        "vote".takeIf { mask.toInt() and 2 != 0 },
        "execute".takeIf { mask.toInt() and 4 != 0 },
    ).joinToString(" + ").ifEmpty { "no permissions" }

    /**
     * Creates a 1-of-1 Squads multisig owned by the wallet, with the generated `multisigCreateV2Instruction`.
     * The wallet is also the create key, so each wallet has one demo multisig and no extra signer is needed.
     * Returns the transaction signature once the network has confirmed it.
     */
    suspend fun createMultisig(sender: ActivityResultSender, onStep: (String) -> Unit): String {
        val (configAddress, config) = programConfig()
        return signSendConfirm(sender, onStep) { owner -> listOf(createInstruction(owner, configAddress, config)) }
    }

    // ---------- Wallet health: rights the wallet gave others over its token accounts ----------

    /** A token account of the wallet whose tokens [delegate] may spend without asking. */
    data class OpenPermission(
        val account: SolanaPublicKey,
        val tokenProgram: SolanaPublicKey,
        val mint: SolanaPublicKey,
        val delegate: SolanaPublicKey,
        val delegatedAmount: ULong,
        val decimals: Int?,
    )

    /**
     * Every open spending permission on [owner]'s token accounts (Token and Token-2022), read with the generated
     * `Token` and `Mint` decoders. Token-2022 accounts start with the same layout, so the first bytes are enough.
     */
    suspend fun openPermissions(owner: SolanaPublicKey): List<OpenPermission> =
        listOf(TokenProgram.PROGRAM_ID, TOKEN_2022).flatMap { program ->
            rpc.tokenAccounts(owner, program).mapNotNull { (address, data) ->
                val account = runCatching { Token.decode(data.copyOf(Token.SIZE)) }.getOrNull() ?: return@mapNotNull null
                val delegate = account.delegate ?: return@mapNotNull null
                if (!account.owner.bytes.contentEquals(owner.bytes)) return@mapNotNull null
                val decimals = rpc.accountData(account.mint)?.let { runCatching { Mint.decode(it.copyOf(Mint.SIZE)).decimals.toInt() }.getOrNull() }
                OpenPermission(address, program, account.mint, delegate, account.delegatedAmount, decimals)
            }
        }

    /** The generated `revokeInstruction`, for the program that holds the account. */
    fun revokeFor(p: OpenPermission, owner: SolanaPublicKey) = revokeInstruction(source = p.account, owner = owner, programId = p.tokenProgram)

    /** What the guard says about revoking [p]: read back from the instruction's bytes, like any transaction. */
    fun revokeAlerts(p: OpenPermission, owner: SolanaPublicKey): List<Alert> = TransactionGuard.check(listOf(revokeFor(p, owner)), owner)

    /** Removes the spending permission [p], signed by the wallet that owns the account. */
    suspend fun revoke(sender: ActivityResultSender, p: OpenPermission, owner: SolanaPublicKey, onStep: (String) -> Unit): String =
        signSendConfirm(sender, onStep) { chosen ->
            require(chosen.bytes.contentEquals(owner.bytes)) { "Pick the wallet ${owner.base58().take(6)}… in the wallet: it owns this token account." }
            listOf(revokeFor(p, owner))
        }

    /**
     * Builds the transaction for the account the user picks in the wallet, has the wallet sign and send it, and
     * waits until the network confirms it. Returns its signature.
     */
    private suspend fun signSendConfirm(
        sender: ActivityResultSender,
        onStep: (String) -> Unit,
        build: suspend (SolanaPublicKey) -> List<com.solana.transaction.TransactionInstruction>,
    ): String {
        var failure: Throwable? = null
        val result = wallet.transact(sender) { auth ->
            runCatching {
                val owner = SolanaPublicKey(auth.accounts.first().publicKey)
                val instructions = build(owner)
                // Fetched inside the wallet session, right before signing: a blockhash only lives about a minute.
                LegacyTransaction.compile(owner, rpc.latestBlockhash(), instructions)
            }.onFailure { failure = it }.getOrNull()?.let { signAndSendTransactions(arrayOf(it)) }
        }
        failure?.let { throw it }
        val signature = when (result) {
            is TransactionResult.Success -> result.payload?.signatures?.firstOrNull()?.let { Base58.encode(it) }
                ?: error("The wallet returned no signature")
            is TransactionResult.NoWalletFound -> error("No Mobile Wallet Adapter wallet found")
            is TransactionResult.Failure -> error(result.message)
        }
        onStep("Sent: $signature")
        repeat(30) {
            val status = rpc.status(signature)
            if (status?.startsWith("failed") == true) error("Transaction $status")
            if (status == "confirmed" || status == "finalized") return signature
            delay(1_000)
        }
        error("Not confirmed after 30 s: $signature")
    }

    companion object {
        val TOKEN_2022 = SolanaPublicKey.from("TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb")
        const val IDENTITY_URI = "https://github.com/solanachetis/codama-kotlin/"
        const val IDENTITY_ICON = "favicon.ico"
        const val IDENTITY_NAME = "codama-kotlin demo"
    }
}
