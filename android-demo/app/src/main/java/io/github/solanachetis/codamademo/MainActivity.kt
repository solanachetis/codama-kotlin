class MainActivity : ComponentActivity() {
    // Must exist before the activity is started: it registers for the wallet's result.
    private lateinit var sender: ActivityResultSender

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        sender = ActivityResultSender(this)
        setContent {
            MaterialTheme(colorScheme = darkColorScheme()) {
                Surface(Modifier.fillMaxSize()) {
                    var network by remember { mutableStateOf(Network.MAINNET) }
                    // One demo per network: switching starts over, the wallet authorizes each network separately.
                    val demo = remember(network) { SquadsDemo(network) }
                    key(network) { DemoScreen(demo, sender, onNetwork = { network = it }) }
                }
            }
        }
    }
}

@Composable
private fun DemoScreen(demo: SquadsDemo, sender: ActivityResultSender, onNetwork: (Network) -> Unit) {
    val scope = rememberCoroutineScope()
    var owner by remember { mutableStateOf<SolanaPublicKey?>(null) }
    var balance by remember { mutableStateOf<Long?>(null) }
    var config by remember { mutableStateOf<Pair<SolanaPublicKey, ProgramConfig>?>(null) }
    var multisig by remember { mutableStateOf<Pair<SolanaPublicKey, Multisig?>?>(null) }
    var status by remember {
        mutableStateOf(
            if (demo.network == Network.MAINNET) "Mainnet: real SOL. Creating the multisig costs about 0.0015 SOL (account rent)."
            else "Devnet: test SOL only. Your wallet must be on devnet too.",
        )
    }
    var busy by remember { mutableStateOf(false) }
    var preview by remember { mutableStateOf<List<String>?>(null) }
    var createAlerts by remember { mutableStateOf<List<Alert>?>(null) }
    var scamAlerts by remember { mutableStateOf<List<Alert>?>(null) }

    fun run(label: String, block: suspend () -> Unit) {
        busy = true
        status = label
        scope.launch {
            runCatching { block() }.onFailure {
                status = if (it.message?.contains("cancelled", ignoreCase = true) == true) "Cancelled in the wallet."
                else "Error: ${it.message}"
            }
            busy = false
        }
    }

    suspend fun refresh(o: SolanaPublicKey) {
        balance = demo.balance(o)
        config = demo.programConfig()
        multisig = demo.multisigOf(o)
        preview = if (multisig?.second == null) demo.preview(o) else null
        createAlerts = if (multisig?.second == null) demo.alertsForCreate(o) else null
    }

    Column(
        Modifier.fillMaxSize().safeDrawingPadding().verticalScroll(rememberScrollState()).padding(20.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp),
    ) {
        Text("codama-kotlin", style = MaterialTheme.typography.headlineMedium)
        Text(
            "A Squads v4 multisig created and read from native Kotlin generated by codama-kotlin, " +
                "signed with Mobile Wallet Adapter.",
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            Network.entries.forEach { n ->
                if (n == demo.network) Button({}) { Text(n.label) }
                else OutlinedButton({ onNetwork(n) }, enabled = !busy) { Text(n.label) }
            }
        }

        val o = owner
        if (o == null) {
            Button({ run("Opening the wallet…") { demo.connect(sender).also { owner = it; refresh(it) }; status = "Connected." } },
                enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Connect wallet (${demo.network.label})") }
        } else {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                    Text("Wallet", style = MaterialTheme.typography.titleMedium)
                    Mono(o.base58())
                    Text("Balance: ${balance?.let { "%.4f SOL".format(it / 1e9) } ?: "…"}")
                }
            }
            config?.let { (address, c) ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text("Squads ProgramConfig (generated decoder)", style = MaterialTheme.typography.titleMedium)
                        Mono(address.base58())
                        Text("Creation fee: ${c.multisigCreationFee} lamports")
                        Text("Treasury:")
                        Mono(c.treasury.base58())
                    }
                }
            }
            multisig?.let { (address, m) ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text("My multisig (generated decoder)", style = MaterialTheme.typography.titleMedium)
                        Mono(address.base58())
                        if (m == null) {
                            Text("Not created yet.")
                        } else {
                            Text("Threshold: ${m.threshold} of ${m.members.size}")
                            Text("Transactions: ${m.transactionIndex} · time lock: ${m.timeLock} s")
                            m.members.forEach { Mono("• ${it.key.base58().take(8)}…  permissions ${it.permissions.mask}") }
                        }
                    }
                }
            }
            val enough = (balance ?: 0L) >= MIN_LAMPORTS
            preview?.let { lines ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text("What you will sign (generated parser)", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "Read back from the instruction's bytes, not from what the app meant to send.",
                            color = MaterialTheme.colorScheme.onSurfaceVariant, fontSize = 12.sp,
                        )
                        lines.forEach { Text(it) }
                        createAlerts?.let { alerts ->
                            Text("Guard", style = MaterialTheme.typography.titleSmall)
                            alerts.forEach { AlertRow(it) }
                        }
                    }
                }
            }
            if (multisig?.second == null && !enough) {
                Text(
                    "Creating the multisig needs about 0.005 SOL on this wallet (rent and fee)." +
                        if (demo.network == Network.DEVNET) " Get test SOL first: the button below, or faucet.solana.com." else "",
                    color = MaterialTheme.colorScheme.error,
                )
            }
            if (multisig?.second == null) {
                Button({
                    run("Building the instruction…") {
                        val sig = demo.createMultisig(sender) { status = it }
                        refresh(o)
                        status = "Created and confirmed: $sig"
                    }
                }, enabled = !busy && enough, modifier = Modifier.fillMaxWidth()) { Text("Create my Squads multisig") }
            }
            if (demo.network == Network.DEVNET) {
                OutlinedButton({ run("Requesting 1 devnet SOL…") { demo.airdrop(o); status = "Airdrop requested."; refresh(o) } },
                    enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Request 1 devnet SOL") }
            }
            OutlinedButton({ run("Refreshing…") { refresh(o); status = "Up to date." } },
                enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Refresh") }
            OutlinedButton({ run("Scanning…") { scamAlerts = demo.scanExampleScam(o); status = "Scanned. Nothing was signed or sent." } },
                enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Scan an example scam (nothing is signed)") }
            scamAlerts?.let { alerts ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        Text("A fake \"claim your airdrop\" transaction", style = MaterialTheme.typography.titleMedium)
                        Text(
                            "What a draining site would ask you to sign. The guard reads it with the generated parsers.",
                            color = MaterialTheme.colorScheme.onSurfaceVariant, fontSize = 12.sp,
                        )
                        alerts.forEach { AlertRow(it) }
                    }
                }
            }
        }
        Text(status, color = MaterialTheme.colorScheme.onSurfaceVariant)
    }
}

/** Multisig account rent (~0.0034 SOL for one member) plus the fee, rounded up. */
private const val MIN_LAMPORTS = 5_000_000L

@Composable
private fun AlertRow(alert: Alert) {
    val (icon, color) = when (alert.level) {
        Level.DANGER -> "🛑" to MaterialTheme.colorScheme.error
        Level.WARNING -> "⚠️" to MaterialTheme.colorScheme.tertiary
        Level.UNCHECKED -> "❔" to MaterialTheme.colorScheme.onSurfaceVariant
        Level.INFO -> "ℹ️" to MaterialTheme.colorScheme.onSurface
    }
    Text("$icon ${alert.message}", color = color)
}

@Composable
private fun Mono(text: String) = Text(text, fontFamily = FontFamily.Monospace, fontSize = 12.sp)
